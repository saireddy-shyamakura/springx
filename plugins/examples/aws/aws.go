// Package aws is an example springx plugin that adds AWS-specific project
// templates, post-generation hooks, and dependency groups.
//
// # How to use this example
//
// Blank-import this package in your main.go (or a dedicated plugins.go file)
// to activate it:
//
//	import _ "github.com/saireddy-shyamakura/springx/plugins/examples/aws"
//
// The plugin registers itself via init(), so no other wiring is needed.
//
// # What this plugin contributes
//
//   - Templates : "aws-lambda", "aws-s3"
//   - Hooks     : "aws-sam"  (generates a SAM template.yaml)
//   - Deps      : "AWS" group with common Spring Cloud AWS starters
