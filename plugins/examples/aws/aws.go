// ── HookPlugin ────────────────────────────────────────────────────────────────

func (p *awsPlugin) Hooks() []postgen.Hook {
	return []postgen.Hook{&samHook{}}
}

// samHook generates a minimal AWS SAM template.yaml so the project can be
// deployed with `sam build && sam deploy` immediately after generation.
type samHook struct{}

func (h *samHook) Name() string { return "aws-sam" }

func (h *samHook) Run(projectPath string, cfg *prompt.ProjectConfig) error {
	content := buildSAMTemplate(cfg)
	dest := filepath.Join(projectPath, "template.yaml")
	if err := os.WriteFile(dest, []byte(content), 0644); err != nil {
		return fmt.Errorf("aws-sam hook: failed to write template.yaml: %w", err)
	}
	return nil
}

func buildSAMTemplate(cfg *prompt.ProjectConfig) string {
	return fmt.Sprintf(`AWSTemplateFormatVersion: '2010-09-09'
Transform: AWS::Serverless-2016-10-31
Description: >
  %s
  SAM template generated by springx aws plugin.

Globals:
  Function:
    Timeout: 30
    MemorySize: 512
    Runtime: java%s
    Architectures:
      - x86_64
    Environment:
      Variables:
        SPRING_PROFILES_ACTIVE: cloud

Resources:
  %sFunction:
    Type: AWS::Serverless::Function
    Properties:
      CodeUri: .
      Handler: org.springframework.cloud.function.adapter.aws.FunctionInvoker::handleRequest
      SnapStart:
        ApplyOn: PublishedVersions
      Events:
        ApiEvent:
          Type: Api
          Properties:
            Path: /{proxy+}
            Method: ANY

Outputs:
  ApiEndpoint:
    Description: API Gateway endpoint URL
    Value: !Sub "https://${ServerlessRestApi}.execute-api.${AWS::Region}.amazonaws.com/Prod/"
`, cfg.ProjectName, cfg.JavaVersion, toPascalCase(cfg.ArtifactID))
}

// toPascalCase converts a kebab-case string to PascalCase for SAM resource names.
func toPascalCase(s string) string {
	if s == "" {
		return "Application"
	}
	result := make([]byte, 0, len(s))
	capitalise := true
	for i := 0; i < len(s); i++ {
		c := s[i]
		if c == '-' || c == '_' {
			capitalise = true
			continue
		}
		if capitalise && c >= 'a' && c <= 'z' {
			c -= 32
		}
		result = append(result, c)
		capitalise = false
	}
	return string(result)
}

